def rx(old): return re.compile('(?:</?mark>)*'.join('(?:<br>)' if c == '\n' else re.escape(c) for c in old))
def tr(text, old, new):
    if new in text: return text, 'already'
    ms = list(rx(old).finditer(text))
    if len(ms) != 1: return text, 'MISS%d' % len(ms)
    a, b = ms[0].span()
    for m in re.finditer(r'<mark>.*?</mark>', text):
        s, e = m.span()
        if s < b and e > a and not (s >= a and e <= b): a = min(a, s); b = max(b, e)
    clean = re.sub(r'</?mark>', '', text[a:b]); o = old.replace('\n', '<br>'); i = clean.find(o)
    if i < 0: return text, 'MISSCLEAN'
    return text[:a] + clean[:i] + new + clean[i + len(o):] + text[b:], 'ok'
