def conv(s):
    return re.sub(r'\[\[(.+?)\]\]', '___', s), re.sub(r'\[\[(.+?)\]\]', r'<span class="key">\1</span>', s)

def card(t, ids, src, d, l, c, z, zj, mn=''):
    ids = ['es-' + x for x in ids]
    for x in ids: assert x in LAB, x
    parts = [re.sub(r'；(?![^\[]*\]\])', '；<br>', x) for x in [d, l, c, z, zj]]
    secs = ''.join('<div class="esb %s"><span class="esl"%s>%s</span><div class="esc">%s</div></div>' % (
        L[k][0], ' title="卓見為自編收尾句，非法條"' if k == 4 else '', L[k][1], parts[k]) for k in range(5))
    b, a = conv(secs)
    esl = [[LAB[x], x] for x in ids if x.startswith('es-fw')]
    x = {"term": t, "blank": b, "answer": a, "src": src, "essay": len(esl), "esl": esl, "qk": [],
         "es5": [[LAB[k], k if k in RID else '', k if k in SID else ''] for k in ids]}
    if mn: x["m"] = mn
    return x

