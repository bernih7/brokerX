# -*- coding: utf-8 -*-
"""土地法考場版自動挑黃底重點（候選）。在去掉標籤後的純文字段落上找，不跨標籤、不含條號。"""
import re
NUM = r'[\d,.]+'
U = r'(?:個月|日|年|%|‰|倍|成|萬元|元|戶|公頃|公畝|平方公尺|人)'
STOP = '，。；：、（）「」'
P = [
 # 法律效果
 ('eff', r'免徵[^%s]{0,14}|免納所得稅|不課徵[^%s]{0,12}|減半徵收|減徵[^%s]{0,10}|免稅|無效|不生效力|失其效力|喪失[^%s]{2,10}|視為[^%s]{2,14}|準用[^%s]{2,16}|有優先(?:購買|承買|承租)權|優先(?:購買|承買|承租)|得請求[^%s]{2,16}|得申請[^%s]{2,16}|得聲請[^%s]{2,16}|得撤銷[^%s]{0,10}|應撤銷[^%s]{0,10}|廢止[^%s]{2,10}|追繳[^%s]{0,10}|退還[^%s]{0,12}|課徵[^%s]{0,12}|應(?:予)?(?:徵收|發給|補償|公告|通知|申報|繳納|辦理|登記)[^%s]{0,16}|不得[^%s]{2,18}|須經[^%s]{2,16}|應經[^%s]{2,16}'.replace('%s', STOP)),
 # 期間、比例、金額（從所在子句開頭標）
 ('num', r'[^%s]{0,14}?%s\s*%s(?:內|以上|以下|以內|為限|前|後|起)?[^%s]{0,10}'.replace('%s',STOP,1).replace('%s',NUM,1).replace('%s',U,1).replace('%s',STOP,1)),
 ('frac', r'[^%s]{0,12}?(?:[一二三四五六七八九十百]+分之[一二三四五六七八九十]+|過半數|半數)[^%s]{0,12}'.replace('%s', STOP)),
 ('def', r'(?<=指)[^%s]{4,30}|(?<=係指)[^%s]{4,30}'.replace('%s', STOP)),
]
P = [(k, re.compile(r)) for k, r in P]
ART = re.compile(r'第\s*\d+條|§')
def cands(text):
    """text: 純文字（不含標籤）。回傳 [(s,e,kind)]"""
    out = []
    for k, rx in P:
        for m in rx.finditer(text):
            s, e = m.span(); seg = text[s:e]
            # 去頭尾連接詞
            while seg and seg[0] in '並且而即故則及或與': s += 1; seg = seg[1:]
            if len(seg) < 3 or len(seg) > 32 or ART.search(seg): continue
            out.append((s, s + len(seg), k))
    return out
