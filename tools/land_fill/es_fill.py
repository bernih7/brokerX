def keys(off,pred):
    out=[]
    for k in off: out.append((k,'q-'+k))
    for tok in re.split(r'[、，]',pred or ''):
        tok=tok.strip()
        if not tok: continue
        m=re.match(r'([PXK])(\d+)(?:～[PXK]?(\d+))?$',tok)
        a,b=int(m.group(2)),int(m.group(3) or m.group(2))
        for n in range(a,b+1):
            lab={'P':'P%02d','X':'X%d','K':'K%d'}[m.group(1)]%n
            rid={'P':'pr-%02d','X':'x-%d','K':'mk-%d'}[m.group(1)]%n
            out.append((lab,rid))
    return [[lab,(rid if rid in RID else ''),(rid if rid in SID else '')] for lab,rid in out]
