#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
2026-10-29（晚）接續 fix_teacher_1：清掉 e102-2 改回老師版後殘留的前後矛盾。

老師擬答把設計費併進直接成本那一邊寫成「180,000,000×**1.03**」，站上原本是照
**§76 的分法**（直接成本＝營造或施工費；間接成本＝規劃設計費＋廣告費銷售費＋
管理費＋稅捐及其他負擔）把設計費放在 M 裡。兩種分法總額相同：
  老師分法：(C＋設計費) 18,540 萬 ＋ 廣銷管稅 11,031 萬 ＝ 29,571 萬
  §76 分法：C 18,000 萬 ＋ M（540＋6,128＋1,226＋3,677＝11,571 萬）＝ 29,571 萬
站上保留 §76 的分法（那才是條文定義），並註明老師的 ×1.03 是同一回事。

修掉三處：
 ① M 的加總還是 §77 版的數字（540＋6,210＋1,242＋3,726＝11,718），與前一句
    已改好的「廣告 6,128／稅捐 1,226／管理 3,677」互相矛盾。
 ② 每坪仍寫「7 億 0,480 萬÷1,600 坪」。
 ③ 小結的每坪寫 44.1 萬，精確值為 441,415 元。

可重複執行。
"""
import sys
from pathlib import Path

PAGE = Path(__file__).resolve().parent.parent.parent / "不動產估價概要_申論題實戰範文.html"

EDITS = [
    ("M 的加總改回 §76 分法（2 處）",
     "M＝540＋6,210＋1,242＋3,726＝<b>11,718 萬</b>（約 1.1718 億）。",
     "依 <b>§76</b> 之分法，M＝設計費 540＋廣告 6,128＋稅捐 1,226＋管理 3,677＝"
     "<b>11,571 萬</b>（約 1.1571 億）；"
     "老師擬答把設計費併進直接成本寫成 1.8 億×1.03＝18,540 萬，"
     "再加廣銷管稅 11,031 萬，<b>總額 29,571 萬完全相同</b>。", 2),

    ("每坪改用 7 億 0,626 萬（2 處）",
     "每坪＝7 億 0,480 萬÷1,600 坪≈",
     "每坪＝706,263,988÷1,600＝441,415 元≈", 2),

    ("小結每坪改精確值",
     "小結</span>V≈7.06 億元，約 44.1 萬/坪。",
     "小結</span>V＝706,263,988 元（約 7.06 億），每坪約 44.14 萬。", 1),

    ("地圖步驟 4 的每坪",
     "（約 44.1 萬/坪）",
     "（約 44.14 萬/坪）", 1),
]


def main():
    s = PAGE.read_text(encoding="utf-8")
    before = len(s)
    done, skip, fail = [], [], []
    for name, old, new, n_exp in EDITS:
        if new in s and old not in s:
            skip.append(name)
            continue
        n = s.count(old)
        if n != n_exp:
            fail.append(f"✗ {name}：原文出現 {n} 次（應為 {n_exp} 次）\n     找的是：{old[:95]}…")
            continue
        s = s.replace(old, new)
        done.append(f"{name}（{n} 處）")
    if fail:
        for f in fail:
            print(f)
        sys.exit("\n有項目對不上，整支腳本不寫檔。")
    PAGE.write_text(s, encoding="utf-8")
    for d in done:
        print("  ✔", d)
    for d in skip:
        print("  －已是新版，略過：", d)
    print(f"寫入 {PAGE.name}：{before} → {len(s)} 字元")


if __name__ == "__main__":
    main()
