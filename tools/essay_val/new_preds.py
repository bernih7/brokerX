def main():
    s = open(PAGE, encoding='utf-8').read()
    D = json.load(open(os.path.join(HERE, 'lj_data.json'), encoding='utf-8'))
    have = {x['k'] for x in D}
    byg = {}
    for c in CARDS:
        if ('id="%s"' % c['id']) in s: print('skip', c['id']); continue
        byg.setdefault(c['grp'], []).append(c)
    for g, cs in byg.items():
        gi = s.index('<details class="tgroup" open data-g="%s"' % g)
        ge = s.index('</details>', gi)
        close = s.rindex('  </div>\n', gi, ge)
        ins = '\n'.join(card_html(c) for c in cs) + '\n'
        s = s[:close] + ins + s[close:]
        # 題數更新
        m = re.search(r'data-total="(\d+)">(\d+)題（含預測(\d+)）', s[gi:])
        a = gi + m.start(); b = gi + m.end()
        tot = int(m.group(1)) + len(cs); pr = int(m.group(3)) + len(cs)
        s = s[:a] + 'data-total="%d">%d題（含預測%d）' % (tot, tot, pr) + s[b:]
    open(PAGE, 'w', encoding='utf-8').write(s)
    for c in CARDS:
        if c['id'] in have: continue
        d = dict(k=c['id'], kind=c['lj']['kind'], subs=c['lj']['subs'], checks=c['lj']['checks'], kw=c['lj']['kw'], mnem=c['lj'].get('mnem', ''))
        D.append(d)
    json.dump(D, open(os.path.join(HERE, 'lj_data.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('cards', len(CARDS), 'lj', len(D))

