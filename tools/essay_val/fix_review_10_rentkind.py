#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
四組外部審稿（2026-10-29）修補 ⑩：租金四卡全缺「正常租金／限定租金」。

這是改完第 ⑨ 批後，被收緊的 check_lj.py 自己抓出來的——先前 kw 檢查把「得分關鍵詞區」
也算進卡內，所以列了內容裡根本沒有的詞也會通過；修掉那個漏洞後才現形。

逐字依據（知識庫《估價_技術規則_全文逐字_§1-§133_20261022》）：
§2⑤ 「正常租金：指具有市場性之不動產，於有意願之租賃雙方，依專業知識、謹慎行動，
      不受任何脅迫，經適當市場行銷及正常租賃條件形成之合理租賃價值，並以貨幣金額
      表示者。」
§2⑥ 「限定租金：指基於**續訂租約**或不動產合併為目的形成之租賃價值，並以貨幣金額
      表示者。」
§6   「……估計租金種類包括正常租金及限定租金。」
§131 「不動產租金估計，應視新訂租約與續訂租約分別為之。」
官方考古 113-5：選項 1「租金估價的價格種類包括正常租金與限定租金兩種」、
      選項 3「續訂租金與正常市場租金不同，故續訂租金屬於限定租金」皆為正確敘述。

另：e101-2 的經濟租金定義原寫「最有效（利）使用方式」，括號把得分關鍵詞
「最有效使用」切開了，閱卷掃詞掃不到——改成「最有效使用（最有效利用）方式」。

可重複執行。
"""
import sys
from pathlib import Path

PAGE = Path(__file__).resolve().parent.parent.parent / "不動產估價概要_申論題實戰範文.html"

RENT_KIND = (
    "租金之<b>價格種類只有兩種</b>：<b>正常租金</b>（§2⑤：具市場性之不動產，於有意願之"
    "租賃雙方依專業知識、謹慎行動，不受脅迫，經適當市場行銷及正常租賃條件形成之合理"
    "租賃價值）與<b>限定租金</b>（§2⑥：基於<b>續訂租約</b>或不動產合併為目的形成之"
    "租賃價值）；§6 明定估計租金種類即此二者。配合 §131「應視新訂租約與續訂租約分別"
    "為之」，<b>新訂租約→正常租金、續訂租約→限定租金</b>（113-5 考過）。"
)

EDITS = [
    # ════ e101-2：關鍵詞「最有效使用」被括號切開 ════
    ("e101-2 經濟租金定義讓「最有效使用」連成一詞（2 處）",
     "不動產於市場上以<b>最有效（利）使用方式</b>利用所能產生之收益",
     "不動產於市場上以<b>最有效使用</b>（最有效利用）方式利用所能產生之收益", 2),

    # ════ e101-2：補租金種類 ════
    ("e101-2 失分點補正常租金／限定租金",
     '<div class="qa-blk qa-trap"><div class="qa-label">▌ 常見失分點</div>\n'
     '        經濟租金是支付租金',
     '<div class="qa-blk qa-trap"><div class="qa-label">▌ 常見失分點</div>\n'
     '        ' + RENT_KIND + '<br>\n        經濟租金是支付租金', 1),

    # ════ e114-1：補租金種類 ════
    ("e114-1 失分點補正常租金／限定租金",
     "另依 §131 須區分新訂與續訂分別估計：§132 新訂3種、§133 續訂4種（含差額分配法）",
     "另依 §131 須區分新訂與續訂分別估計：§132 新訂3種、§133 續訂4種（含差額分配法）。"
     "<br>" + RENT_KIND, 1),

    # ════ e110-2：審稿同樣指出缺（關鍵詞未列，但內容值得補） ════
    ("e110-2 失分點補正常租金／限定租金",
     "差額分配法只適用續訂（§133）",
     "差額分配法只適用續訂（§133）。<br>" + RENT_KIND, 1),
]


def main():
    s = PAGE.read_text(encoding="utf-8")
    before = len(s)
    done, skip, fail = [], [], []
    for name, old, new, n_exp in EDITS:
        if new in s and old not in s:
            skip.append(name)
            continue
        n = s.count(old)
        if n != n_exp:
            fail.append(f"✗ {name}：原文出現 {n} 次（應為 {n_exp} 次）\n     找的是：{old[:95]}…")
            continue
        s = s.replace(old, new)
        done.append(f"{name}（{n} 處）")
    if fail:
        for f in fail:
            print(f)
        sys.exit("\n有項目對不上，整支腳本不寫檔。")
    PAGE.write_text(s, encoding="utf-8")
    for d in done:
        print("  ✔", d)
    for d in skip:
        print("  －已是新版，略過：", d)
    print(f"寫入 {PAGE.name}：{before} → {len(s)} 字元")


if __name__ == "__main__":
    main()
