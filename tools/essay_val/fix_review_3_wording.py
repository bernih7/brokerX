def main():
    s = PAGE.read_text(encoding="utf-8")
    before = len(s)
    done, skip, fail = [], [], []
    for name, old, new, n_exp in EDITS:
        if new in s and old not in s:
            skip.append(name)
            continue
        n = s.count(old)
        if n != n_exp:
            fail.append(f"✗ {name}：原文出現 {n} 次（應為 {n_exp} 次）\n     找的是：{old[:90]}…")
            continue
        s = s.replace(old, new)
        done.append(f"{name}（{n} 處）")
    if fail:
        for f in fail:
            print(f)
        sys.exit("\n有項目對不上，整支腳本不寫檔。")
    PAGE.write_text(s, encoding="utf-8")
    for d in done:
        print("  ✔", d)
    for d in skip:
        print("  －已是新版，略過：", d)
    print(f"寫入 {PAGE.name}：{before} → {len(s)} 字元")


if __name__ == "__main__":
    main()
