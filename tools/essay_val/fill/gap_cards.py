LAB_L = "L 地價調查估計規則"
def js(x):  # 單引號字串
    assert "'" not in x and '\\' not in x, x
    return "'" + x + "'"
def card_js(cid, x):
    b = re.sub(r'\[\[(.+?)\]\]', '___', x['s']); a = re.sub(r'\[\[(.+?)\]\]', r'<span class="key">\1</span>', x['s'])
    assert b.count('___') == a.count('class="key"') > 0
    return ("      {\n        cid:'%s',\n        term:%s,\n        blank:%s,\n        answer:%s,\n        src:%s, mc:%d, essay:0, gap:1\n      },\n"
            % (cid, js(x['term']), js(b), js(a), js(x['src']), x['mc']))
