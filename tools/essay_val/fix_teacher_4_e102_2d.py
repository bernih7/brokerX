# -*- coding: utf-8 -*-
"""
2026-10-29（晚）接續 fix_teacher_1／2／3：刪掉 e102-2 假設段裡重複的兩段。

把頭條改回老師版的過程中，fix_teacher_1 新增的「⚠️ 參考：§77 字面…」、
原本就有的「§77 明定廣告銷售費…V≈7.05 億」、fix_teacher_3 重寫的
「⚠️ 另外兩個版本…」三段在講同一件事，疊在一起。
只留：①老師版說明 ②「另外兩個版本」（已含 §77 字面版與不折現版的精確數字）。

另把其他地方的「7.05 億」統一寫成精確值 7.0480 億，避免與頭條 7.06 億混淆時
看不出差多少。

可重複執行。
"""
import sys
from pathlib import Path

PAGE = Path(__file__).resolve().parent.parent.parent / "不動產估價概要_申論題實戰範文.html"

EDITS = [
    ("刪掉重複的 §77 參考段（2 處）",
     "<br>⚠️ 參考：§77 字面是「按<b>總銷售金額</b>乘以相關費率」，"
     "若嚴格照字面用題給的 12.42 億計費用，V＝704,796,828（7.0480 億），"
     "與老師版差 146.7 萬；條文既無明文，依老師版作答。",
     "", 2),
    ("刪掉原有的 §77 結論段（2 處）",
     "<br><b>§77 明定廣告銷售費、稅捐、管理費按「總銷售金額」乘費率，"
     "而 §75 之預期總銷售金額即題給之 12.42 億</b>，故費用以 12.42 億為基礎"
     "（M≈1.1718 億），<b>V≈7.05 億</b>。",
     "", 2),

    # ── 其餘提到 7.05 的地方改精確值 ──
    ("地圖步驟 5 三個數字改精確值",
     "寫明假設與費用基礎；7.06／7.05／7.18 億",
     "寫明假設與費用基礎；7.0626／7.0480／7.1812 億", 1),
    ("採分點改精確值",
     "代入</span>寫明假設與費用基礎：本解 7.06 億；費用按題給 12.42 億約 7.05 億；"
     "不折現約 7.18 億（官方採哪種查不到）",
     "代入</span>寫明假設與費用基礎：<b>老師擬答 706,263,988（7.0626 億）</b>；"
     "費用若按題給 12.42 億（§77 字面）＝7.0480 億；完全不折現＝7.1812 億", 1),
    ("速寫摘要改精確值",
     "本解視12.42億為一年後價格先折現、費用按折現後S（7.06億）；"
     "費用改按題給12.42億約7.05億；不折現約7.18億——須寫明假設與費用基礎",
     "<b>老師擬答</b>：視 12.42 億為一年後價格先折現、費用也按折現後 S → "
     "<b>706,263,988 元（7.0626 億，每坪 44.14 萬）</b>；"
     "費用若改按題給 12.42 億（§77 字面）＝7.0480 億；完全不折現＝7.1812 億"
     "——<b>務必寫明費用的計算基礎</b>（老師自註「技術規則並無明確規定」）", 1),
]


def main():
    s = PAGE.read_text(encoding="utf-8")
    before = len(s)
    done, skip, fail = [], [], []
    for name, old, new, n_exp in EDITS:
        if old not in s and (new == "" or new in s):
            skip.append(name)
            continue
        n = s.count(old)
        if n != n_exp:
            fail.append(f"✗ {name}：原文出現 {n} 次（應為 {n_exp} 次）\n     找的是：{old[:95]}…")
            continue
        s = s.replace(old, new)
        done.append(f"{name}（{n} 處）")
    if fail:
        for f in fail:
            print(f)
        sys.exit("\n有項目對不上，整支腳本不寫檔。")
    PAGE.write_text(s, encoding="utf-8")
    for d in done:
        print("  ✔", d)
    for d in skip:
        print("  －已是新版，略過：", d)
    print(f"寫入 {PAGE.name}：{before} → {len(s)} 字元")


if __name__ == "__main__":
    main()
