"""
2026-10-29（晚）接續 fix_teacher_1／2：e102-2 最後兩處收尾。

① 每坪單價的小數算錯：706,263,988÷1,600＝441,415 元＝**44.14 萬**，不是 44.05 萬
   （44.05 萬是 §77 版 704,796,828÷1,600 的值，換回老師版時沒跟著改）。
② 「兩個備用版本」那段邏輯顛倒了——它的①寫「費用若按折現後 S 計 → 7.06 億」，
   而 7.06 億現在就是頭條（老師擬答）。而且「官方評分採哪一種查不到」已不成立：
   使用者提供的補習班老師擬答就是標準答案。整段重寫成「另外兩個版本僅供理解差異」。

可重複執行。
"""
import sys
from pathlib import Path

PAGE = Path(__file__).resolve().parent.parent.parent / "不動產估價概要_申論題實戰範文.html"

EDITS = [
    ("每坪改 44.14 萬（2 處）",
     "441,415 元≈<b>44.05 萬</b>。",
     "441,415 元≈<b>44.14 萬</b>。", 2),

    ("重寫「兩個備用版本」（2 處）",
     "⚠️ 兩個備用版本（官方評分採哪一種查不到，作答一定要寫明假設與費用基礎）："
     "①費用若按折現後 S 計 → V≈7.06 億（§81 已用 ÷(1＋i) 處理資金成本，"
     "費用再按折現值算有重複計價之嫌）；②若視 12.42 億為價格日期之金額、不折現 "
     "→ V≈7.18 億。1.94% 已含施工 1 年，不必再乘。",
     "⚠️ 另外兩個版本（<b>老師擬答已是標準答案，這兩個只是用來理解差異在哪</b>）："
     "①若嚴格照 <b>§77</b> 字面「按總銷售金額乘費率」、用題給的 12.42 億計費用 → "
     "V＝704,796,828（7.0480 億），與老師版差 <b>146.7 萬</b>；"
     "②若把 12.42 億視為價格日期之金額、完全不折現（費用也用 12.42 億）→ "
     "V≈718,123,000（7.1812 億）。<b>1.94% 已含施工 1 年，不必再乘。</b>", 2),

    ("清掉銜接詞「以下為原記之其他假設」（2 處）",
     "（以下為原記之其他假設）",
     "", 2),

    ("更正結論段「官方評分採哪一種查不到」",
     "，V 約 7.18 億；另若費用直接按題給 12.42 億計（S 仍折現），M≈1.1718 億、"
     "V 約 7.05 億。官方評分採哪一種查不到，作答時請寫明假設與費用基礎。",
     "，V 約 7.18 億；另若費用直接按題給 12.42 億計（S 仍折現、照 §77 字面），"
     "M≈1.1718 億、V 約 7.0480 億。<strong>補習班老師擬答採「費用配合折現後之 S」，"
     "得 706,263,988 元，本卡即以此為標準答案</strong>；老師並自註"
     "「技術規則並無明確規定」，故作答時<strong>務必寫明費用的計算基礎</strong>。", 1),
]


def main():
    s = PAGE.read_text(encoding="utf-8")
    before = len(s)
    done, skip, fail = [], [], []
    for name, old, new, n_exp in EDITS:
        if old not in s and (new == "" or new in s):
            skip.append(name)
            continue
        n = s.count(old)
        if n != n_exp:
            fail.append(f"✗ {name}：原文出現 {n} 次（應為 {n_exp} 次）\n     找的是：{old[:95]}…")
            continue
        s = s.replace(old, new)
        done.append(f"{name}（{n} 處）")
    if fail:
        for f in fail:
            print(f)
        sys.exit("\n有項目對不上，整支腳本不寫檔。")
    PAGE.write_text(s, encoding="utf-8")
    for d in done:
        print("  ✔", d)
    for d in skip:
        print("  －已是新版，略過：", d)
    print(f"寫入 {PAGE.name}：{before} → {len(s)} 字元")


if __name__ == "__main__":
    main()
