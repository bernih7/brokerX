def main():
    D = json.load(io.open(JS, encoding='utf-8'))
    idx = {'%s-%s' % (q['y'], q['n']): q for q in D['q']}
    bad = []
    for qid, i, new in EXP:
        q = idx.get(qid)
        if q is None: bad.append('找不到 ' + qid); continue
        exp = q.get('exp') or []
        if i >= len(exp): bad.append('%s 無第 %d 選項' % (qid, i + 1)); continue
        if '<b>' in new or '**' in new: bad.append('%s 含 <b>/**' % qid); continue
        exp[i] = new; q['exp'] = exp
    for qid, (ref, law) in REF.items():
        q = idx.get(qid)
        if q is None: bad.append('找不到 ' + qid); continue
        if ref is not None: q['ref'] = ref
        if law is not None: q['law'] = law
    # 條文庫：公寓大廈施行細則「細則§5」與「§5」為同一條重複收錄，留 §5
    LFP = os.path.join(HERE, 'law', 'lawfull.json')
    LF = json.load(io.open(LFP, encoding='utf-8'))
    drop = [k for k in list(LF) if k == '公寓大廈施行細則 細則§5' and '公寓大廈施行細則 §5' in LF]
    for k in drop: del LF[k]
    if bad:
        print('✗ 中止，未寫檔：'); [print('  ', b) for b in bad]; sys.exit(1)
    io.open(JS, 'w', encoding='utf-8').write(json.dumps(D, ensure_ascii=False, indent=1))
    io.open(LFP, 'w', encoding='utf-8').write(json.dumps(LF, ensure_ascii=False, indent=1))
    print('第四批：%d 處選項解析、%d 題 ref／law；條文庫去重 %s' % (len(EXP), len(REF), drop or '無'))

if __name__ == '__main__':
    main()
