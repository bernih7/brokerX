def artbody(key):
    lines = [x for x in L[key]['text'].strip().split('\n') if x.strip()]
    if len(lines) == 1:
        return '<p>' + lines[0] + '</p>'
    h, i = '', 0
    for p in lines:
        if KUAN.match(p):
            h += '<p style="margin-left:1.6em">%s</p>' % p
        else:
            h += '<p>%s %s</p>' % (CIR[i] if i < len(CIR) else '・', p)
            i += 1
    return h


