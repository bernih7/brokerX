def main():
    D = json.load(io.open(JS, encoding='utf-8'))
    idx = {}
    for q in D['q']:
        idx['%s-%s' % (q['y'], q['n'])] = q

    bad = []
    for qid, i, new in EXP:
        q = idx.get(qid)
        if q is None:
            bad.append('找不到題目 ' + qid); continue
        exp = q.get('exp') or []
        if i >= len(exp):
            bad.append('%s 沒有第 %d 個選項解析' % (qid, i + 1)); continue
        if '<b>' in new or '**' in new:
            bad.append('%s-%s 新解析含 <b> 或 **' % (qid, 'ABCD'[i])); continue
        exp[i] = new
        q['exp'] = exp
    for qid, (ref, law) in REF.items():
        q = idx.get(qid)
        if q is None:
            bad.append('找不到題目 ' + qid); continue
        q['ref'] = ref
        if law is not None:
            q['law'] = law
    if bad:
        print('✗ 中止，未寫檔：'); [print('  ', b) for b in bad]; sys.exit(1)

    io.open(JS, 'w', encoding='utf-8').write(
        json.dumps(D, ensure_ascii=False, indent=1))
    print('已修正 %d 處選項解析、%d 題 ref／law（共 %d 題）'
          % (len(EXP), len(REF), len(set([x[0] for x in EXP]) | set(REF))))

if __name__ == '__main__':
    main()
