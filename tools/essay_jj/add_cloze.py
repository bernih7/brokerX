for t in re.findall(r'"term": "([^"]+)"', '\n'.join(H + D)):
    pat = re.compile(r'\s*\{\s*"term": "%s"[\s\S]*?\n   \},' % re.escape(t))
    s, n = pat.subn('', s)
    if n: print('移除舊題', t)


def insert(sec_id, cards):
    global s
    m = re.search(r'"id": "%s",[\s\S]{0,300}?"cards": \[\n' % sec_id, s)
    assert m, '找不到篇 ' + sec_id
    p = m.end()
    s = s[:p] + ',\n'.join(cards) + ',\n' + s[p:]


