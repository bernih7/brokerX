hits = {(k, i): 0 for k, v in FIX.items() for i in range(len(v))}

def fix_text(cid, s):
    for i, (a, b) in enumerate(FIX[cid]):
        if a in s:
            hits[(cid, i)] += s.count(a); s = s.replace(a, b)
    for rx, fn in RX.get(cid, []): s = rx.sub(fn, s)
    return s

def walk(cid, o):
    if isinstance(o, str): return fix_text(cid, o)
    if isinstance(o, list): return [walk(cid, x) for x in o]
    if isinstance(o, dict): return {k: walk(cid, v) for k, v in o.items()}
    return o

