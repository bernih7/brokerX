    qs = json.loads(m.group(2))
    assert json.dumps(qs, ensure_ascii=False) == m.group(2), pg + ' 序列化格式不同，改用別的方式'
    out = []
    for q in qs:
        k = '%d-%d' % (q['year'], q['qnum'])
        if k in DROP: continue
        if k in FIX:
            a, ex, ref, _ = FIX[k]
            q['answer'] = a; q['explains'] = dict(zip('ABCD', ex)); q['ref'] = ref
        out.append(q)
    s = s[:m.start(2)] + json.dumps(out, ensure_ascii=False) + s[m.end(2):]
    io.open(f, 'w', encoding='utf-8').write(s)
    print(pg, len(qs), '→', len(out))
